#!/usr/bin/env python3
"""Render this project's Claude Code conversations to chat.md.

Run by the Stop hook in .claude/settings.json after every Claude reply
(it reads the hook's JSON on stdin for the transcript path), or by hand:

    python3 scripts/chat_to_md.py            # all sessions of this repo
    python3 scripts/chat_to_md.py --out x.md

Only the human messages and Claude's written answers are kept: no tool
calls, tool output, thinking or system reminders. E-mail addresses and
anything that looks like a key or connection string are redacted, because
chat.md is committed to a shared repo.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DIR = os.path.expanduser(
    "~/.claude/projects/" + re.sub(r"[^A-Za-z0-9]", "-", REPO))

STRIP = [
    re.compile(r"<system-reminder>.*?</system-reminder>", re.S),
    re.compile(r"<(command-[a-z-]+|local-command-[a-z-]+)>.*?</\1>", re.S),
    re.compile(r"</?pasted_content[^>]*>"),
]
REDACT = [
    (re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"), "[email]"),
    (re.compile(r"(AccountKey|SharedAccessKey|sig|password|secret|token)=[^;&\s]+", re.I), r"\1=[redacted]"),
    (re.compile(r"\b(sk-[A-Za-z0-9_-]{16,}|gh[pousr]_[A-Za-z0-9]{20,})\b"), "[redacted]"),
    (re.compile(r"\b[A-Za-z0-9+/]{60,}={0,2}"), "[redacted]"),
    (re.compile(r"\b[a-z0-9-]+(\.z\d+\.web|\.blob|\.queue|\.table|\.file|\.dfs)?\.core\.windows\.net\S*"), "[azure-storage-url]"),
    (re.compile(r"\basketnodedata\w*"), "[storage-account]"),
]


def clean(text: str) -> str:
    for rx in STRIP:
        text = rx.sub("", text)
    for rx, rep in REDACT:
        text = rx.sub(rep, text)
    return text.strip()


def read_session(path):
    """(first timestamp, title, [(role, timestamp, text)])"""
    msgs, title, first = [], None, None
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            try:
                d = json.loads(line)
            except ValueError:
                continue
            t = d.get("type")
            if t == "ai-title":
                title = d.get("aiTitle") or d.get("title") or title
                continue
            if t not in ("user", "assistant") or d.get("isMeta") or d.get("isSidechain"):
                continue
            m = d.get("message") or {}
            c = m.get("content")
            if isinstance(c, str):
                parts = [c]
            elif isinstance(c, list):
                parts = [x.get("text", "") for x in c if x.get("type") == "text"]
            else:
                continue
            text = clean("\n\n".join(parts))
            if not text or text.startswith("Base directory for this skill"):
                continue
            ts = d.get("timestamp") or ""
            first = first or ts
            msgs.append((m.get("role") or t, ts, text))
    return first, title, msgs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=None, help="transcript folder (default: this repo's)")
    ap.add_argument("--out", default=os.path.join(REPO, "chat.md"))
    a = ap.parse_args()

    tdir = a.dir
    if tdir is None and not sys.stdin.isatty():
        try:
            hook = json.load(sys.stdin)
            tdir = os.path.dirname(hook.get("transcript_path", "")) or None
        except ValueError:
            pass
    tdir = tdir or DEFAULT_DIR

    sessions = [read_session(p) for p in glob.glob(os.path.join(tdir, "*.jsonl"))]
    sessions = sorted((s for s in sessions if s[2]), key=lambda s: s[0])

    out = ["# Chat log", "",
           "Conversations with Claude Code in this repo, oldest first. Generated by "
           "`scripts/chat_to_md.py` after every reply; tool output is left out and "
           "e-mails/keys are redacted. Do not edit by hand.", ""]
    for first, title, msgs in sessions:
        out += ["---", "", f"## {first[:10]} {first[11:16]} UTC" + (f" — {title}" if title else ""), ""]
        for role, ts, text in msgs:
            who = "**You**" if role == "user" else "**Claude**"
            out += [f"### {who} · {ts[11:16]}", "", text, ""]
    tmp = a.out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    os.replace(tmp, a.out)


if __name__ == "__main__":
    main()
