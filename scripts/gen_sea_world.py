N_SHADER = 18


def spectrum(sea):
    import rclpy
    from rclpy.parameter import Parameter
    from sim.sea_state_node import SeaStateNode
    rclpy.init()
    n = SeaStateNode(parameter_overrides=[Parameter("sea_state", value=sea)])
    comps = list(zip(n.a, n.kx, n.ky, n.w, n.phase))
    hs = n.hs
    n.destroy_node()
    rclpy.shutdown()
    comps.sort(key=lambda c: -c[0])
    return comps[:N_SHADER], hs


def write_grid(path, x0, x1, y0, y1, step):
    nx = int((x1 - x0) / step) + 1
    ny = int((y1 - y0) / step) + 1
    with open(path, "w") as f:
        f.write("# sea surface grid (displaced by waves_vs.glsl)\n")
        for j in range(ny):
            y = y0 + j * step
            for i in range(nx):
                f.write(f"v {x0 + i * step:.2f} {y:.2f} 0\n")
        f.write("vn 0 0 1\n")
        for j in range(ny - 1):
            for i in range(nx - 1):
                a = j * nx + i + 1
                b, c, d = a + 1, a + nx, a + nx + 1
                f.write(f"f {a}//1 {b}//1 {d}//1\nf {a}//1 {d}//1 {c}//1\n")
    return nx * ny


def write_shaders(out, comps, hs):
    arr = lambda vals: ", ".join(f"{v:.6f}" for v in vals)
    n = len(comps)
    a, kx, ky, w, ph = zip(*comps)
    vs = f"""#version 330
// Generated by scripts/gen_sea_world.py: the {n} biggest wave components of
// sim/sea_state_node. eta = sum a cos(kx x + ky y - w t + phase), x east, y north.
in vec4 vertex;
uniform mat4 worldviewproj_matrix;
uniform float time;
out block {{ vec3 pos; vec3 nrm; float eta; }} outVs;
out gl_PerVertex {{ vec4 gl_Position; }};
const int N = {n};
const float A[N]  = float[N]({arr(a)});
const float KX[N] = float[N]({arr(kx)});
const float KY[N] = float[N]({arr(ky)});
const float W[N]  = float[N]({arr(w)});
const float P[N]  = float[N]({arr(ph)});
void main() {{
  vec4 v = vertex;
  float eta = 0.0, sx = 0.0, sy = 0.0;
  for (int i = 0; i < N; ++i) {{
    float p = KX[i] * v.x + KY[i] * v.y - W[i] * time + P[i];
    eta += A[i] * cos(p);
    sx  -= A[i] * KX[i] * sin(p);
    sy  -= A[i] * KY[i] * sin(p);
  }}
  v.z = eta;
  outVs.pos = v.xyz;
  outVs.nrm = normalize(vec3(-sx, -sy, 1.0));
  outVs.eta = eta;
  gl_Position = worldviewproj_matrix * v;
}}
"""
    fs = f"""#version 330
in block {{ vec3 pos; vec3 nrm; float eta; }} inPs;
out vec4 fragColor;
const float HS = {max(hs, 0.05):.3f};
void main() {{
  vec3 n = normalize(inPs.nrm);
  vec3 sun = normalize(vec3(0.4, -0.3, 0.85));
  float diff = clamp(dot(n, sun), 0.0, 1.0);
  vec3 deep = vec3(0.02, 0.13, 0.22);
  vec3 shallow = vec3(0.07, 0.36, 0.45);
  float h = clamp(inPs.eta / HS + 0.5, 0.0, 1.0);
  vec3 col = mix(deep, shallow, h) * (0.45 + 0.75 * diff);
  float steep = 1.0 - n.z;
  float foam = smoothstep(0.35, 0.6, inPs.eta / HS) * smoothstep(0.02, 0.10, steep);
  col = mix(col, vec3(0.92, 0.95, 0.97), foam);
  vec3 refl = reflect(-sun, n);
  col += vec3(0.5) * pow(clamp(refl.z, 0.0, 1.0), 40.0);
  fragColor = vec4(col, 1.0);
}}
"""
    with open(os.path.join(out, "waves_vs.glsl"), "w") as f:
        f.write(vs)
    with open(os.path.join(out, "waves_fs.glsl"), "w") as f:
        f.write(fs)


