"""Write a Gazebo world for one sea state: animated waves + the mission buoys.

Runs inside the ROS container (it borrows the wave spectrum from
sim/sea_state_node, so the waves you SEE are the waves that move the boat:
same components, same phases, same sim clock).

  python3 scripts/gen_sea_world.py --sea rough --out /workspace/boat_data/sim/world_rough <route.geojson>...

Writes <out>/sea.sdf, <out>/sea_grid.obj, <out>/waves_vs.glsl, <out>/waves_fs.glsl.
Paths in the world are absolute /workspace/... paths: the Gazebo server (ROS
container) and the GUI (scripts/sim_gui.sh, Docker) both mount the repo there.

The sea surface is a flat grid displaced in a vertex shader (Gazebo's
ShaderParam system, TIME = sim time) by the biggest components of the
spectrum; the physics uses all of them.
"""
